-- Seções da loja (Jardim, Hidráulica, ...)
CREATE TABLE cl_secao (
    id_secao     NUMBER(4)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nm_secao     VARCHAR2(60)  NOT NULL,
    ds_cor       VARCHAR2(7)   NOT NULL,
    CONSTRAINT pk_cl_secao PRIMARY KEY (id_secao),
    CONSTRAINT uk_cl_secao_nome UNIQUE (nm_secao)
);

-- Mapa da loja como grafo ponderado: vértices
CREATE TABLE cl_no_mapa (
    id_no        NUMBER(6)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cd_no        VARCHAR2(20)  NOT NULL,
    tp_no        VARCHAR2(20)  NOT NULL,
    nr_x         NUMBER(5)     NOT NULL,
    nr_y         NUMBER(5)     NOT NULL,
    CONSTRAINT pk_cl_no_mapa PRIMARY KEY (id_no),
    CONSTRAINT uk_cl_no_mapa_cd UNIQUE (cd_no),
    CONSTRAINT ck_cl_no_mapa_tp CHECK (tp_no IN ('ENTRADA', 'PASSAGEM', 'CORREDOR', 'ATENDIMENTO', 'CAIXA'))
);

-- Mapa da loja: arestas (não direcionadas, distância em metros)
CREATE TABLE cl_aresta_mapa (
    id_no_origem   NUMBER(6)    NOT NULL,
    id_no_destino  NUMBER(6)    NOT NULL,
    nr_distancia_m NUMBER(6,1)  NOT NULL,
    CONSTRAINT pk_cl_aresta_mapa PRIMARY KEY (id_no_origem, id_no_destino),
    CONSTRAINT fk_cl_aresta_origem FOREIGN KEY (id_no_origem) REFERENCES cl_no_mapa (id_no),
    CONSTRAINT fk_cl_aresta_destino FOREIGN KEY (id_no_destino) REFERENCES cl_no_mapa (id_no),
    CONSTRAINT ck_cl_aresta_dist CHECK (nr_distancia_m > 0)
);

CREATE TABLE cl_corredor (
    id_corredor  NUMBER(4)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nr_corredor  NUMBER(3)     NOT NULL,
    id_secao     NUMBER(4)     NOT NULL,
    id_no        NUMBER(6)     NOT NULL,
    CONSTRAINT pk_cl_corredor PRIMARY KEY (id_corredor),
    CONSTRAINT uk_cl_corredor_nr UNIQUE (nr_corredor),
    CONSTRAINT fk_cl_corredor_secao FOREIGN KEY (id_secao) REFERENCES cl_secao (id_secao),
    CONSTRAINT fk_cl_corredor_no FOREIGN KEY (id_no) REFERENCES cl_no_mapa (id_no)
);

-- Produto (supertipo). tp_disponibilidade é o discriminador do subtipo:
-- PRONTA_ENTREGA = o cliente leva na hora; MOSTRUARIO = só exposição, entrega posterior
CREATE TABLE cl_produto (
    id_produto          NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cd_sku              VARCHAR2(12)  NOT NULL,
    nm_produto          VARCHAR2(120) NOT NULL,
    ds_produto          VARCHAR2(400),
    nm_marca            VARCHAR2(40)  NOT NULL,
    fl_marca_propria    CHAR(1)       DEFAULT 'N' NOT NULL,
    vl_preco            NUMBER(10,2)  NOT NULL,
    ds_unidade          VARCHAR2(20)  NOT NULL,
    id_corredor         NUMBER(4)     NOT NULL,
    nr_prateleira       NUMBER(2)     NOT NULL,
    tp_atendimento      VARCHAR2(20)  NOT NULL,
    tp_disponibilidade  VARCHAR2(20)  DEFAULT 'PRONTA_ENTREGA' NOT NULL,
    ds_palavras_chave   VARCHAR2(400),
    CONSTRAINT pk_cl_produto PRIMARY KEY (id_produto),
    CONSTRAINT uk_cl_produto_sku UNIQUE (cd_sku),
    CONSTRAINT fk_cl_produto_corredor FOREIGN KEY (id_corredor) REFERENCES cl_corredor (id_corredor),
    CONSTRAINT ck_cl_produto_mp CHECK (fl_marca_propria IN ('S', 'N')),
    CONSTRAINT ck_cl_produto_preco CHECK (vl_preco > 0),
    CONSTRAINT ck_cl_produto_atend CHECK (tp_atendimento IN ('AUTONOMO', 'APOIO_PARCIAL', 'DEPENDE_VENDEDOR')),
    CONSTRAINT ck_cl_produto_disp CHECK (tp_disponibilidade IN ('PRONTA_ENTREGA', 'MOSTRUARIO'))
);

-- 1:1 com produto. Estoque do sistema x o que há de fato na prateleira (a diferença é a ruptura)
CREATE TABLE cl_estoque (
    id_produto      NUMBER(8)  NOT NULL,
    qt_sistema      NUMBER(6)  DEFAULT 0 NOT NULL,
    qt_gondola      NUMBER(6)  DEFAULT 0 NOT NULL,
    dt_atualizacao  TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cl_estoque PRIMARY KEY (id_produto),
    CONSTRAINT fk_cl_estoque_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto) ON DELETE CASCADE,
    CONSTRAINT ck_cl_estoque_qt CHECK (qt_sistema >= 0 AND qt_gondola >= 0)
);

-- Autorrelacionamento N:N: produto -> produto equivalente (usado quando a prateleira está vazia)
CREATE TABLE cl_produto_similar (
    id_produto  NUMBER(8)  NOT NULL,
    id_similar  NUMBER(8)  NOT NULL,
    CONSTRAINT pk_cl_produto_similar PRIMARY KEY (id_produto, id_similar),
    CONSTRAINT fk_cl_similar_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto) ON DELETE CASCADE,
    CONSTRAINT fk_cl_similar_similar FOREIGN KEY (id_similar) REFERENCES cl_produto (id_produto) ON DELETE CASCADE,
    CONSTRAINT ck_cl_similar_dif CHECK (id_produto <> id_similar)
);

-- Autorrelacionamento N:N: produto -> item que costuma ser comprado junto (venda complementar)
CREATE TABLE cl_produto_complementar (
    id_produto      NUMBER(8)     NOT NULL,
    id_complementar NUMBER(8)     NOT NULL,
    ds_motivo       VARCHAR2(200) NOT NULL,
    CONSTRAINT pk_cl_produto_compl PRIMARY KEY (id_produto, id_complementar),
    CONSTRAINT fk_cl_compl_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto) ON DELETE CASCADE,
    CONSTRAINT fk_cl_compl_compl FOREIGN KEY (id_complementar) REFERENCES cl_produto (id_produto) ON DELETE CASCADE,
    CONSTRAINT ck_cl_compl_dif CHECK (id_produto <> id_complementar)
);

-- Projeto do cliente montado pelo assistente (anônimo, sem dados pessoais)
CREATE TABLE cl_projeto (
    id_projeto    NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    ds_titulo     VARCHAR2(120)  NOT NULL,
    ds_problema   VARCHAR2(1000),
    dt_criacao    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cl_projeto PRIMARY KEY (id_projeto)
);

-- Entidade associativa que resolve PROJETO N:N PRODUTO
CREATE TABLE cl_item_projeto (
    id_projeto     NUMBER(10)    NOT NULL,
    id_produto     NUMBER(8)     NOT NULL,
    qt_item        NUMBER(5)     NOT NULL,
    fl_essencial   CHAR(1)       DEFAULT 'S' NOT NULL,
    ds_motivo      VARCHAR2(300),
    CONSTRAINT pk_cl_item_projeto PRIMARY KEY (id_projeto, id_produto),
    CONSTRAINT fk_cl_item_projeto FOREIGN KEY (id_projeto) REFERENCES cl_projeto (id_projeto) ON DELETE CASCADE,
    CONSTRAINT fk_cl_item_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto),
    CONSTRAINT ck_cl_item_qt CHECK (qt_item > 0),
    CONSTRAINT ck_cl_item_ess CHECK (fl_essencial IN ('S', 'N'))
);

-- Número da senha mostrado ao cliente ("Senha 042")
CREATE SEQUENCE seq_cl_senha_chamado START WITH 1 INCREMENT BY 1 MAXVALUE 999 CYCLE NOCACHE;

-- Chamado de vendedor, com o contexto do projeto do cliente
CREATE TABLE cl_chamado (
    id_chamado     NUMBER(10)     GENERATED ALWAYS AS IDENTITY,
    nr_senha       NUMBER(3)      NOT NULL,
    id_projeto     NUMBER(10),
    id_corredor    NUMBER(4)      NOT NULL,
    id_produto     NUMBER(8),
    ds_motivo      VARCHAR2(500)  NOT NULL,
    st_chamado     VARCHAR2(20)   DEFAULT 'ABERTO' NOT NULL,
    nm_vendedor    VARCHAR2(60),
    dt_abertura    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    dt_aceite      TIMESTAMP,
    dt_conclusao   TIMESTAMP,
    CONSTRAINT pk_cl_chamado PRIMARY KEY (id_chamado),
    CONSTRAINT fk_cl_chamado_projeto FOREIGN KEY (id_projeto) REFERENCES cl_projeto (id_projeto) ON DELETE SET NULL,
    CONSTRAINT fk_cl_chamado_corredor FOREIGN KEY (id_corredor) REFERENCES cl_corredor (id_corredor),
    CONSTRAINT fk_cl_chamado_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto),
    CONSTRAINT ck_cl_chamado_st CHECK (st_chamado IN ('ABERTO', 'A_CAMINHO', 'CONCLUIDO', 'CANCELADO'))
);

-- Registros de prateleira vazia feitos pelos clientes (alimentam a reposição e o painel de indicadores)
CREATE TABLE cl_ruptura (
    id_ruptura   NUMBER(10)  GENERATED ALWAYS AS IDENTITY,
    id_produto   NUMBER(8)   NOT NULL,
    id_projeto   NUMBER(10),
    tp_desfecho  VARCHAR2(20) NOT NULL,
    dt_registro  TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cl_ruptura PRIMARY KEY (id_ruptura),
    CONSTRAINT fk_cl_ruptura_produto FOREIGN KEY (id_produto) REFERENCES cl_produto (id_produto),
    CONSTRAINT fk_cl_ruptura_projeto FOREIGN KEY (id_projeto) REFERENCES cl_projeto (id_projeto) ON DELETE SET NULL,
    CONSTRAINT ck_cl_ruptura_desf CHECK (tp_desfecho IN ('PENDENTE', 'SIMILAR', 'COMPRA_ONLINE', 'VENDEDOR', 'DESISTIU'))
);

CREATE INDEX ix_cl_produto_corredor ON cl_produto (id_corredor);
CREATE INDEX ix_cl_chamado_status ON cl_chamado (st_chamado, dt_abertura);
CREATE INDEX ix_cl_ruptura_produto ON cl_ruptura (id_produto);
